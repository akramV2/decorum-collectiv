const assert=require('node:assert/strict');
const {spawn}=require('node:child_process');
const fs=require('node:fs');
const path=require('node:path');
const {chromium}=require(process.env.LATENCE_PLAYWRIGHT_PATH||'playwright');
const server=spawn(process.execPath,['tools/admin-preview.cjs'],{env:{...process.env,PORT:'4179'},stdio:['ignore','pipe','pipe']});
const output=path.resolve('../../outputs/latence');fs.mkdirSync(output,{recursive:true});
(async()=>{
 await new Promise((resolve,reject)=>{server.stdout.once('data',resolve);server.once('error',reject);server.stderr.once('data',x=>reject(Error(x.toString())));});
 const browser=await chromium.launch({headless:true,channel:process.env.LATENCE_BROWSER_CHANNEL||'chrome'});
 try {
 const page=await browser.newPage({viewport:{width:1440,height:1000}}), errors=[];page.on('pageerror',e=>errors.push(e.message));page.on('dialog',d=>d.accept());
 await page.goto('http://127.0.0.1:4179/');
 await page.getByRole('heading',{name:'L’équilibre des rubriques'}).waitFor();
 await page.screenshot({path:path.join(output,'admin-dashboard-updated.png')});
 await page.getByRole('button',{name:'Toutes les publications',exact:true}).click();
 await page.locator('.workbench-filters select[name=category]').selectOption("À l'usage");
 assert.equal(await page.locator('.admin-row').count(),1);
 await page.locator('.workbench-filters select[name=status]').selectOption('draft');
 assert.equal(await page.locator('.admin-row').count(),0);
 await page.getByRole('button',{name:'Réinitialiser les filtres'}).click();
 assert.equal(await page.locator('.admin-row').count(),4);
 await page.getByRole('button',{name:'Calendrier',exact:true}).click();
 await page.getByRole('button',{name:/Programmé · Les objets/}).waitFor();
 await page.getByRole('button',{name:'Mois suivant →'}).click();
 await page.getByRole('button',{name:'Aujourd’hui',exact:true}).click();
 await page.screenshot({path:path.join(output,'admin-calendrier.png')});
 await page.getByRole('button',{name:'Tableau de bord',exact:true}).click();
 await page.getByRole('button',{name:'Écrire une publication'}).click();
 await page.getByLabel('Modèle de rédaction').selectOption('2');
 await page.getByRole('button',{name:'Appliquer le modèle'}).click();
 assert.equal(await page.locator('[name=category]').inputValue(),'Sélection');
 assert.equal(await page.locator('[name=type]').inputValue(),'SÉLECTION');
 await page.locator('[name=title]').fill('Un texte à récupérer');
 await page.locator('[name=excerpt]').fill('Chapeau de travail.');
 await page.locator('[name=content]').fill('<h2>Une idée</h2><p>Texte important.</p>');
 await page.reload();
 await page.getByRole('button',{name:'Écrire une publication'}).click();
 await page.getByRole('button',{name:'Récupérer en brouillon'}).click();
 assert.equal(await page.locator('[name=title]').inputValue(),'Un texte à récupérer');
 assert.equal(await page.locator('[name=status]').inputValue(),'draft');
 assert.equal(await page.locator('[name=type]').inputValue(),'SÉLECTION');
 assert.equal(await page.locator('[name=category]').inputValue(),'Sélection');
 assert.ok((await page.locator('[name=content]').inputValue()).includes('Texte important'));
 await page.getByRole('button',{name:'Brouillons & programmation',exact:true}).click();
 await page.getByRole('button',{name:'Continuer à modifier'}).click();
 assert.equal(await page.locator('#article-editor').count(),1);
 await page.keyboard.press('Control+s');
 await page.getByText('Brouillon enregistré.',{exact:true}).waitFor();
 await page.waitForFunction(()=>!document.querySelector('.workbench-recovery'));
 await page.screenshot({path:path.join(output,'admin-editor-updated.png')});
 await page.setViewportSize({width:390,height:844});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1),false);
 await page.screenshot({path:path.join(output,'admin-editor-mobile.png'),fullPage:true});
 await page.getByRole('button',{name:'Calendrier',exact:true}).click();
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1),false);
 assert.equal(await page.locator('.outside-month:visible').count(),0);
 assert.deepEqual(errors,[]);
 console.log('Admin integration passed: dashboard, compound filters, calendar, templates, recovery, leave guard, keyboard save, mobile, no JS errors.');
 } finally {await browser.close();server.kill();}
})().catch(e=>{console.error(e);server.kill();process.exitCode=1;});

